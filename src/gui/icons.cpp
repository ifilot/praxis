#include "icons.h"

#include <QFile>

QIcon bluecurve_icon(const QString& name) {
    QIcon icon;
    for(int size : {16, 24, 32, 48}) {
        const QString path = QString(":/assets/icons/bluecurve/%1/%2.png").arg(size).arg(name);
        if(QFile::exists(path)) {
            icon.addFile(path, QSize(size, size));
        }
    }
    return icon;
}
